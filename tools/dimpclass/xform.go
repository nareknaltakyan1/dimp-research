package dimpclass

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strings"
)

// xformItem is one state-schema change that needs a transformer.
type xformItem struct {
	kind             string // "type" | "var"
	pkg              *Package
	name             string
	oldT, newT       *TypeDecl
	oldType, newType string
}

var numericTypes = map[string]bool{
	"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true,
	"float32": true, "float64": true, "byte": true, "rune": true, "uintptr": true,
	"time.Duration": true,
}

// genXform emits a Go source skeleton that maps the old state layout to the
// new one field by field (S5 state transfer). Both versions share one import
// path, so the old and new layouts are mirrored as <T>V1 / <T>V2.
func genXform(items []xformItem) string {
	mirrored := map[string]bool{}
	for _, it := range items {
		if it.kind == "type" && it.oldT.Kind == "struct" && it.newT.Kind == "struct" {
			mirrored[it.name] = true
		}
	}
	imports := map[string]bool{}
	var body bytes.Buffer
	sort.SliceStable(items, func(i, j int) bool { return items[i].name < items[j].name })
	for _, it := range items {
		switch {
		case it.kind == "var":
			imports["encoding/json"], imports["errors"] = true, true
			fn := "TransformVar" + exportName(it.name)
			fmt.Fprintf(&body, "// ---- package-level var %s.%s: %s -> %s\n\n", it.pkg.Path, it.name, it.oldType, it.newType)
			fmt.Fprintf(&body, "// %s converts the serialised old value of %s to the new type.\n", fn, it.name)
			fmt.Fprintf(&body, "func %s(in json.RawMessage) (json.RawMessage, error) {\n", fn)
			fmt.Fprintf(&body, "\t// TODO(var-type): decode %s, convert to %s, re-encode.\n", it.oldType, it.newType)
			fmt.Fprintf(&body, "\treturn nil, errors.New(%q)\n}\n\n", "TODO: transformer for "+it.name)
		case it.oldT.Kind == "struct" && it.newT.Kind == "struct":
			genStructXform(&body, it, mirrored, imports)
		default:
			imports["errors"] = true
			fn := "Transform" + exportName(it.name)
			fmt.Fprintf(&body, "// ---- type %s.%s: %s -> %s\n\n", it.pkg.Path, it.name, it.oldT.Underlying, it.newT.Underlying)
			fmt.Fprintf(&body, "// %s converts one old %s value. TODO(type): representation changed.\n", fn, it.name)
			fmt.Fprintf(&body, "func %s(in any) (any, error) {\n\treturn nil, errors.New(%q)\n}\n\n", fn, "TODO: transformer for "+it.name)
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by dimpclass (S8). State-transformer SKELETON for an S5 handoff.\n")
	out.WriteString("// Review and complete every TODO before use. The old (V1) and new (V2) layouts\n")
	out.WriteString("// are mirrored here because both versions of the package share one import path;\n")
	out.WriteString("// the old process exports V1 values in its state envelope, the new process\n")
	out.WriteString("// decodes them, calls Transform*, and installs the V2 values.\n\n")
	out.WriteString("package statexform\n\n")
	if len(imports) > 0 {
		out.WriteString("import (\n")
		for _, p := range sortedKeys(imports) {
			fmt.Fprintf(&out, "\t%q\n", p)
		}
		out.WriteString(")\n\n")
	}
	out.Write(body.Bytes())
	src := out.Bytes()
	if f, err := format.Source(src); err == nil {
		return string(f)
	}
	return string(src)
}

func exportName(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

var identRe = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*`)
var selRe = regexp.MustCompile(`\b([A-Za-z_][A-Za-z0-9_]*)\.[A-Za-z_]`)

// mirrorType renames mirrored local types to their V1/V2 names.
func mirrorType(src, suffix string, mirrored map[string]bool) string {
	return identRe.ReplaceAllStringFunc(src, func(id string) string {
		if mirrored[id] {
			return id + suffix
		}
		return id
	})
}

func noteImports(src string, imps map[string]string, imports map[string]bool) {
	for _, m := range selRe.FindAllStringSubmatch(src, -1) {
		if p, ok := imps[m[1]]; ok {
			imports[p] = true
		}
	}
}

func genStructXform(b *bytes.Buffer, it xformItem, mirrored map[string]bool, imports map[string]bool) {
	ot, nt := it.oldT, it.newT
	fmt.Fprintf(b, "// ---- %s.%s (state: %s)\n\n", it.pkg.Path, it.name, firstNonEmpty(nt.StateWhy, ot.StateWhy, "in-memory state"))
	writeMirror := func(t *TypeDecl, suffix, which string) {
		fmt.Fprintf(b, "// %s%s mirrors the %s layout of %s.\n", it.name, suffix, which, it.name)
		fmt.Fprintf(b, "type %s%s struct {\n", it.name, suffix)
		for _, f := range t.Fields {
			ty := mirrorType(f.TypeSrc, suffix, mirrored)
			noteImports(f.TypeSrc, t.imports, imports)
			tag := ""
			if f.Tag != "" {
				tag = " `" + f.Tag + "`"
			}
			if f.Embedded {
				fmt.Fprintf(b, "\t%s%s\n", ty, tag)
			} else {
				fmt.Fprintf(b, "\t%s %s%s\n", f.Name, ty, tag)
			}
		}
		b.WriteString("}\n\n")
	}
	writeMirror(ot, "V1", "old (v1)")
	writeMirror(nt, "V2", "new (v2)")

	of := map[string]Field{}
	for _, f := range ot.Fields {
		of[f.Name] = f
	}
	nf := map[string]bool{}
	fn := "Transform" + exportName(it.name)
	fmt.Fprintf(b, "// %s maps one old %s to the new layout.\n", fn, it.name)
	fmt.Fprintf(b, "func %s(in %sV1) (%sV2, error) {\n\tvar out %sV2\n", fn, it.name, it.name, it.name)
	usesErr := false
	for _, f := range nt.Fields {
		nf[f.Name] = true
		o, ok := of[f.Name]
		if !ok {
			fmt.Fprintf(b, "\t// TODO(added): out.%s (%s) has no v1 source; the zero value is kept. Derive it from in if possible.\n", f.Name, f.TypeSrc)
			continue
		}
		if o.Type != f.Type {
			if numericTypes[o.TypeSrc] && numericTypes[f.TypeSrc] {
				fmt.Fprintf(b, "\tout.%s = %s(in.%s) // TODO(retyped): %s -> %s; check units and range\n", f.Name, f.TypeSrc, f.Name, o.TypeSrc, f.TypeSrc)
			} else {
				fmt.Fprintf(b, "\t// TODO(retyped): out.%s (%s) <- in.%s (%s): write the conversion\n", f.Name, f.TypeSrc, f.Name, o.TypeSrc)
			}
			continue
		}
		// same declared type: does it embed a mirrored (changed) type?
		inner := ""
		for _, id := range identRe.FindAllString(f.TypeSrc, -1) {
			if mirrored[id] {
				inner = id
			}
		}
		if inner == "" {
			fmt.Fprintf(b, "\tout.%s = in.%s\n", f.Name, f.Name)
			continue
		}
		usesErr = true
		tf := "Transform" + exportName(inner)
		switch t := f.TypeSrc; {
		case t == inner:
			fmt.Fprintf(b, "\tif v, err := %s(in.%s); err != nil {\n\t\treturn out, err\n\t} else {\n\t\tout.%s = v\n\t}\n", tf, f.Name, f.Name)
		case t == "*"+inner:
			fmt.Fprintf(b, "\tif in.%s != nil {\n\t\tv, err := %s(*in.%s)\n\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n\t\tout.%s = &v\n\t}\n", f.Name, tf, f.Name, f.Name)
		case strings.HasPrefix(t, "map[") && (strings.HasSuffix(t, "]"+inner) || strings.HasSuffix(t, "]*"+inner)):
			ptr := strings.HasSuffix(t, "]*"+inner)
			fmt.Fprintf(b, "\tout.%s = make(%s, len(in.%s))\n\tfor k, e := range in.%s {\n", f.Name, mirrorType(t, "V2", mirrored), f.Name, f.Name)
			if ptr {
				fmt.Fprintf(b, "\t\tif e == nil {\n\t\t\tout.%s[k] = nil\n\t\t\tcontinue\n\t\t}\n\t\tv, err := %s(*e)\n\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n\t\tout.%s[k] = &v\n\t}\n", f.Name, tf, f.Name)
			} else {
				fmt.Fprintf(b, "\t\tv, err := %s(e)\n\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n\t\tout.%s[k] = v\n\t}\n", tf, f.Name)
			}
		case t == "[]"+inner || t == "[]*"+inner:
			ptr := t == "[]*"+inner
			fmt.Fprintf(b, "\tout.%s = make(%s, len(in.%s))\n\tfor i, e := range in.%s {\n", f.Name, mirrorType(t, "V2", mirrored), f.Name, f.Name)
			if ptr {
				fmt.Fprintf(b, "\t\tif e == nil {\n\t\t\tcontinue\n\t\t}\n\t\tv, err := %s(*e)\n\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n\t\tout.%s[i] = &v\n\t}\n", tf, f.Name)
			} else {
				fmt.Fprintf(b, "\t\tv, err := %s(e)\n\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n\t\tout.%s[i] = v\n\t}\n", tf, f.Name)
			}
		default:
			fmt.Fprintf(b, "\t// TODO(nested): out.%s (%s) contains changed type %s; apply %s element-wise\n", f.Name, t, inner, tf)
		}
	}
	for _, f := range ot.Fields {
		if !nf[f.Name] {
			fmt.Fprintf(b, "\t// DROPPED: in.%s (%s) has no v2 destination; confirm it is safe to discard.\n", f.Name, f.TypeSrc)
		}
	}
	_ = usesErr
	b.WriteString("\treturn out, nil\n}\n\n")
}
